
import { ResultSetHeader } from "mysql2";
import { ClientError } from "../models/client-error";
import { CredentialsModel } from "../models/credentials-model";
import { Role, StatusCode } from "../models/enums";
import { UserModel } from "../models/user-model";
import { cyber } from "../utils/cyber";
import { dal } from "../utils/dal";

// Handles user registration and login:
class AuthService {

    // Register a new user and generate a JWT:
    public async register(user: UserModel): Promise<string> {

        // Validate user details:
        user.validate();

        // Prevent registration with an existing email:
        const isTaken = await this.isEmailTaken(user.email);

        if (isTaken) {
            throw new ClientError(StatusCode.Conflict, "Email already exists.");
        }

        // Assign the regular User role to prevent self-registration as admin:
        user.roleId = Role.User;

        // Hash the password before storing it in MySQL:
        user.password = cyber.hash(user.password);

        // Insert the new user using parameterized SQL:
        const sql = `insert into users(firstName, lastName, email, password, roleId) values(?, ?, ?, ?, ?)`;
        const values = [user.firstName, user.lastName, user.email, user.password, user.roleId];
        const result = await dal.execute(sql, values) as ResultSetHeader;

        // Set the user ID generated by MySQL:
        user.userId = result.insertId;

        // Generate a JWT so the new user can access protected routes:
        const token = cyber.generateToken(user);
        return token;
    }

    // Log in an existing user and generate a JWT:
    public async login(credentials: CredentialsModel): Promise<string> {

        // Validate the submitted credentials:
        credentials.validate();

        // Hash the password to compare it with the stored hash:
        credentials.password = cyber.hash(credentials.password);

        // Find a user matching the email and hashed password:
        const sql = `select * from users where email = ? and password = ?`;
        const values = [credentials.email, credentials.password];
        const users = await dal.execute(sql, values) as UserModel[];
        const user = users[0];

        // Reject incorrect login details:
        if (!user) {
            throw new ClientError(StatusCode.Unauthorized, "Incorrect email or password.");
        }

        // Generate a signed JWT for the authenticated user:
        const token = cyber.generateToken(user);
        return token;
    }

    // Check whether an email address is already registered:
    private async isEmailTaken(email: string): Promise<boolean> {
        const sql = `select exists(select * from users where email = ?) as isTaken`;
        const result = await dal.execute(sql, [email]) as { isTaken: number }[];
        return result[0].isTaken === 1;
    }

}

export const authService = new AuthService();
